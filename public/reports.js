// WP23: Reports Suite (screen, print / save as PDF, export to CSV)

const REPORT_TYPES = {
  inventory: { label: 'Document Inventory', status: true, type: true },
  routing: { label: 'Routing' },
  approval: { label: 'Approval' },
  release: { label: 'Release' },
  performance: { label: 'Tracking and Performance' },
};
let currentReport = null;

function loadReports() {
  const keep = (sel) => $(sel).value;
  if (!$('#rp-type').options.length)
    $('#rp-type').innerHTML = Object.entries(REPORT_TYPES).map(([k, v]) => `<option value="${k}">${v.label}</option>`).join('');
  const opt = (items, all) => `<option value="">${all}</option>` + items.map((i) => `<option value="${i.id}">${esc(i.name)}</option>`).join('');
  const dept = keep('#rp-dept');
  $('#rp-dept').innerHTML = opt(lookups.departments, 'All departments');
  $('#rp-dept').value = dept;
  const typ = keep('#rp-doctype');
  $('#rp-doctype').innerHTML = opt(lookups.types, 'All types');
  $('#rp-doctype').value = typ;
  if (!$('#rp-status').options.length)
    $('#rp-status').innerHTML = '<option value="">All statuses</option>' +
      ['Registered', 'Routed', 'Received', 'Returned', 'Approved', 'Rejected', 'Released', 'Archived'].map((s) => `<option>${s}</option>`).join('');
  toggleReportFilters();
  runReport();
}

function toggleReportFilters() {
  const def = REPORT_TYPES[$('#rp-type').value];
  $('#rp-status-label').hidden = !def.status;
  $('#rp-doctype-label').hidden = !def.type;
}

const pad2 = (n) => String(n).padStart(2, '0');
const reportDate = (d) => {
  if (!d) return '';
  const x = new Date(d);
  return `${x.getFullYear()}-${pad2(x.getMonth() + 1)}-${pad2(x.getDate())} ${pad2(x.getHours())}:${pad2(x.getMinutes())}`;
};
const reportCell = (col, value) => {
  if (value === null || value === undefined || value === '') return col.kind === 'num' ? '-' : '';
  return col.kind === 'date' ? reportDate(value) : String(value);
};

async function runReport() {
  const key = $('#rp-type').value;
  const def = REPORT_TYPES[key];
  const p = new URLSearchParams();
  const parts = [];
  const add = (param, sel, text) => { const v = $(sel).value; if (v) { p.set(param, v); parts.push(text(v)); } };
  add('from', '#rp-from', (v) => `from ${v}`);
  add('to', '#rp-to', (v) => `to ${v}`);
  add('dept', '#rp-dept', () => `department: ${$('#rp-dept').selectedOptions[0].textContent}`);
  if (def.status) add('status', '#rp-status', (v) => `status: ${v}`);
  if (def.type) add('type', '#rp-doctype', () => `type: ${$('#rp-doctype').selectedOptions[0].textContent}`);
  try {
    currentReport = await api(`/reports/${key}?${p}`);
  } catch (err) { toast(err.message, true); return; }
  currentReport.key = key;
  currentReport.filters = parts.length ? parts.join(', ') : 'none (all records)';
  currentReport.generated = `${user.name} on ${reportDate(new Date())}`;
  renderReport();
}

function renderReport() {
  const r = currentReport;
  const body = r.rows.length
    ? r.rows.map((row) => `<tr>${r.columns.map((c) => `<td>${esc(reportCell(c, row[c.key]))}</td>`).join('')}</tr>`).join('')
    : `<tr><td class="empty" colspan="${r.columns.length}">No records for the selected filters.</td></tr>`;
  $('#rp-out').innerHTML = `
    <div class="report-head"><h2>${esc(r.title)}</h2>
      <p class="muted">Filters: ${esc(r.filters)}<br>Generated by ${esc(r.generated)}</p></div>
    <div class="report-sum">${r.summary.map((s) => `<div><b>${esc(String(s.value))}</b>${esc(s.label)}</div>`).join('')}</div>
    <div class="report-table-wrap"><table><thead><tr>${r.columns.map((c) => `<th>${esc(c.label)}</th>`).join('')}</tr></thead>
      <tbody>${body}</tbody></table></div>`;
  $('#rp-print').disabled = false;
  $('#rp-csv').disabled = false;
}

// CSV that opens correctly in Excel
function reportToCsv(r) {
  const q = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
  const lines = [[r.title], [`Filters: ${r.filters}`], [`Generated by ${r.generated}`], [],
    r.columns.map((c) => c.label),
    ...r.rows.map((row) => r.columns.map((c) => reportCell(c, row[c.key]))),
    [], ['Summary'], ...r.summary.map((s) => [s.label, s.value])];
  return lines.map((l) => l.map(q).join(',')).join('\r\n');
}

function downloadReportCsv() {
  const blob = new Blob(['\ufeff' + reportToCsv(currentReport)], { type: 'text/csv;charset=utf-8' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = `${currentReport.key}-report-${reportDate(new Date()).slice(0, 10)}.csv`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(a.href);
}

function printReport() {
  document.body.classList.add('print-report');
  try { window.print(); } finally { document.body.classList.remove('print-report'); }
}

$('#rp-type').addEventListener('change', () => { toggleReportFilters(); runReport(); });
$('#rp-run').addEventListener('click', runReport);
$('#rp-csv').addEventListener('click', downloadReportCsv);
$('#rp-print').addEventListener('click', printReport);
